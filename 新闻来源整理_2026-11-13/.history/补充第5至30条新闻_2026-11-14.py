escape = lambda value: html.escape(str(value), quote=True)

def render_section(event, paragraphs):
    event_id = event["id"]
    def render_paragraph(text):
        return "<p>" + re.sub(r"\[(\d+)\]", lambda m:
            f'<a class="ref" href="#{event_id}-S{m.group(1)}">[{m.group(1)}]</a>',
            escape(text)) + "</p>"
    sources_html = []
    for i, item in enumerate(event["sources"], 1):
        limited = ' <span class="limited">（原站访问受限，可结合其他来源核对）</span>' if "受限" in item.get("access", "") else ""
        sources_html.append(
            f'<li id="{event_id}-S{i}"><a class="source" href="{escape(item["url"])}" '
            'target="_blank" rel="noopener noreferrer">' + escape(item["title"]) +
            '</a> <span class="meta">— ' + escape(item["publisher"]) + '，' +
            escape(item["date"]) + '</span>' + limited + '</li>')
    return (f'<section id="{event_id}">\n<h2>{int(event_id[1:])}. ' +
            escape(event["title"]) + ' <span class="category">' +
            escape(event["category"]) + '</span></h2>\n' +
            "\n".join(render_paragraph(text) for text in paragraphs) +
            '\n<ol>' + "\n".join(sources_html) + '</ol>\n</section>')

